@Testcontainers(disabledWithoutDocker = true)
class OracleDumpRestoreTest {
    private static final String RESTORED_USER = "restored";
    private static final String RESTORED_PASSWORD = "Restored_pw1";
    private static final List<String> QUERIES = List.of(
            "SELECT id, email, name, bio, big_bio, photo, big_photo, balance, ratio, created, updated, seen, raw_id, dur, total FROM customers ORDER BY id",
            "SELECT * FROM \"Order Items\" ORDER BY id");

    @org.testcontainers.junit.jupiter.Container
    static final OracleContainer DB = new OracleContainer("gvenzl/oracle-free:23-slim-faststart")
            .withStartupTimeout(java.time.Duration.ofMinutes(6));

    @BeforeAll
    static void seed() throws Exception {
        // what a DBA runs once to allow a consistent (AS OF SCN) dump
        Container.ExecResult grant = DB.execInContainer("sh", "-c",
                "printf 'ALTER SESSION SET CONTAINER=%s;\\nGRANT EXECUTE ON DBMS_FLASHBACK TO %s;\\n' | sqlplus -s / as sysdba"
                        .formatted(DB.getDatabaseName(), DB.getUsername()));
        assertThat(grant.getStdout()).doesNotContain("ORA-");
        try (Connection system = connect("system", DB.getPassword())) {
            exec(system,
                    "CREATE USER " + RESTORED_USER + " IDENTIFIED BY " + RESTORED_PASSWORD + " QUOTA UNLIMITED ON USERS",
                    "GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW, CREATE PROCEDURE, CREATE TRIGGER TO " + RESTORED_USER);
        }
        try (Connection c = connect(DB.getUsername(), DB.getPassword())) {
            exec(c,
                    "CREATE SEQUENCE invoice_seq START WITH 100 INCREMENT BY 5",
                    """
                    CREATE TABLE customers (
                      id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                      email VARCHAR2(200) NOT NULL CONSTRAINT uq_email UNIQUE,
                      name NVARCHAR2(200),
                      bio CLOB,
                      big_bio CLOB,
                      photo BLOB,
                      big_photo BLOB,
                      balance NUMBER(12, 2) CONSTRAINT ck_balance CHECK (balance >= -1000),
                      ratio BINARY_DOUBLE,
                      created DATE,
                      updated TIMESTAMP(6),
                      seen TIMESTAMP(3) WITH TIME ZONE,
                      raw_id RAW(16),
                      dur INTERVAL DAY TO SECOND,
                      total NUMBER GENERATED ALWAYS AS (balance * 2) VIRTUAL)""",
                    """
                    CREATE TABLE "Order Items" (
                      id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      customer_id NUMBER NOT NULL CONSTRAINT fk_items_customer REFERENCES customers(id),
                      qty NUMBER,
                      note VARCHAR2(100))""",
                    "CREATE INDEX ix_note ON \"Order Items\"(note)",
                    "CREATE VIEW v_cust AS SELECT id, email FROM customers",
                    "CREATE OR REPLACE FUNCTION f_double(x NUMBER) RETURN NUMBER IS BEGIN RETURN x * 2; END;",
                    """
                    CREATE OR REPLACE TRIGGER trg_items BEFORE INSERT ON "Order Items" FOR EACH ROW
                    BEGIN IF :NEW.note IS NULL THEN :NEW.note := 'from trigger'; END IF; END;""",
                    "SELECT invoice_seq.NEXTVAL FROM dual");

            String bigBio = ("Line with 'quotes' & ampersand\n\nafter a blank line; ünïcødé 😀\n").repeat(1200);
            byte[] bigPhoto = new byte[10_000];
            new Random(7).nextBytes(bigPhoto);
            try (PreparedStatement ps = c.prepareStatement("""
                    INSERT INTO customers (email, name, bio, big_bio, photo, big_photo, balance, ratio, created, updated, seen, raw_id, dur)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, TIMESTAMP '2024-02-29 13:45:01', TIMESTAMP '2026-06-03 23:56:18.451137',
                            TIMESTAMP '2026-06-03 23:56:18.451 +03:00', HEXTORAW('00FF0D0A27'), INTERVAL '1 02:03:04.5' DAY TO SECOND)""")) {
                ps.setString(1, "a@x.io");
                ps.setString(2, "O'Brien \"q\" & co");
                ps.setString(3, "short bio");
                ps.setString(4, bigBio);
                ps.setBytes(5, new byte[]{1, 2, 3});
                ps.setBytes(6, bigPhoto);
                ps.setBigDecimal(7, new java.math.BigDecimal("-12.50"));
                ps.setString(8, "NaN"); // the driver refuses NaN via setDouble; Oracle converts the text
                ps.executeUpdate();
            }
            exec(c, "INSERT INTO customers (email) VALUES ('b@x.io')",
                    "INSERT INTO \"Order Items\" (customer_id, qty, note) SELECT 1, level, 'n' || level FROM dual CONNECT BY level <= 1500",
                    "COMMIT");
        }
    }

    @Test
    void dumpRestoresToIdenticalSchema(@TempDir Path tmp) throws Exception {
        DBConfig config = new DBConfig(DBType.ORACLE, DB.getHost(), DB.getOraclePort(), DB.getUsername(), DB.getPassword(),
                DB.getDatabaseName(), 2);
        DumpReport report = DumpTestSupport.dumper(new OracleDumpStrategy(), DumpTestSupport.properties(3, 500))
                .dump(config, tmp.resolve("db"));

        assertThat(report.failures()).isEmpty();
        assertThat(report.objectsTotal()).isEqualTo(2);
        try (Connection system = connect("system", DB.getPassword())) {
            assertThat(single(system, "SELECT count(*) FROM v$session WHERE program = 'AppBackup'"))
                    .as("connections left open after the dump").isEqualTo("0");
        }

        int n = 0;
        for (Path file : DumpTestSupport.restoreOrder(tmp.resolve("db"))) {
            String target = "/tmp/r%03d.sql".formatted(n++);
            DB.copyFileToContainer(MountableFile.forHostPath(file), target);
            Container.ExecResult result = DB.execInContainer("sh", "-c", "sqlplus -s %s/%s@//localhost:1521/%s < %s"
                    .formatted(RESTORED_USER, RESTORED_PASSWORD, DB.getDatabaseName(), target));
            assertThat(result.getExitCode()).as("restore of %s: %s %s", file.getFileName(), result.getStdout(), result.getStderr())
                    .isZero();
        }

        try (Connection source = connect(DB.getUsername(), DB.getPassword());
             Connection restored = connect(RESTORED_USER, RESTORED_PASSWORD)) {
            for (String query : QUERIES) {
                assertThat(rows(restored, query)).as(query).isEqualTo(rows(source, query));
            }
            // Oracle restarts cached sequences past the cache (like Data Pump); it must never reissue a used value
            assertThat(Long.parseLong(single(restored, "SELECT invoice_seq.NEXTVAL FROM dual"))).as("sequence continues")
                    .isGreaterThanOrEqualTo(105);
            exec(restored, "INSERT INTO customers (email) VALUES ('new@x.io')");
            assertThat(single(restored, "SELECT id FROM customers WHERE email = 'new@x.io'")).as("identity continues").isEqualTo("3");
            assertThatThrownBy(() -> exec(restored, "INSERT INTO customers (id, email) VALUES (50, 'z@x.io')"))
                    .as("GENERATED ALWAYS is restored").hasMessageContaining("ORA-32795");
            exec(restored, "INSERT INTO \"Order Items\" (customer_id, qty) VALUES (1, 1)");
            assertThat(single(restored, "SELECT note FROM \"Order Items\" WHERE id = 1501")).isEqualTo("from trigger");
            assertThat(single(restored, "SELECT f_double(21) FROM dual")).isEqualTo("42");
            assertThat(single(restored, "SELECT count(*) FROM v_cust")).isEqualTo("3");
            assertThat(single(restored, "SELECT count(*) FROM user_indexes WHERE index_name = 'IX_NOTE'")).isEqualTo("1");
            assertThatThrownBy(() -> exec(restored, "INSERT INTO \"Order Items\" (customer_id) VALUES (999)"))
                    .hasMessageContaining("ORA-02291");
        }
    }

    private static Connection connect(String user, String password) throws SQLException {
        return DriverManager.getConnection(DB.getJdbcUrl(), user, password);
    }
}
